/**
 * Regenerates src/lib/photo-sizes.ts — the intrinsic pixel size of every photo
 * in public/, so <Image> can emit a srcset and reserve the right box.
 * The helpers that read it are hand-written in src/lib/photos.ts.
 *
 * Run after adding, replacing or re-cropping any photo:
 *   node scripts/generate-photo-manifest.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const PUBLIC = path.join(import.meta.dirname, "..", "public");
const OUT = path.join(import.meta.dirname, "..", "src", "lib", "photo-sizes.ts");
const PHOTO = /\.(jpe?g|png|webp|avif)$/i;
// Logos and favicons are drawn at fixed sizes and never go through <Image>.
const SKIP = /^(favicon|apple-touch-icon)/i;

const files = (await readdir(PUBLIC, { withFileTypes: true }))
  .filter((e) => e.isFile() && PHOTO.test(e.name) && !SKIP.test(e.name))
  .map((e) => e.name)
  .sort();

const rows = [];
for (const name of files) {
  const { width, height } = await sharp(path.join(PUBLIC, name)).metadata();
  rows.push(`  "/${name}": { width: ${width}, height: ${height} },`);
}

await writeFile(
  OUT,
  `// GENERATED by scripts/generate-photo-manifest.mjs — do not edit by hand.
// Re-run it whenever a photo in public/ is added, replaced or re-cropped.
// The helpers that read this live in src/lib/photos.ts.

export type PhotoSize = { width: number; height: number };

export const PHOTO_SIZES: Record<string, PhotoSize> = {
${rows.join("\n")}
};
`,
  "utf8",
);

console.log(`photo-sizes.ts: ${rows.length} photos`);
